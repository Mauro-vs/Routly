// Imágenes mínimas hechas a mano para los tests: solo las cabeceras que lee utils/imageFile.js
export function fakePng(width, height) {
  const header = Buffer.alloc(33);
  Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]).copy(header, 0);
  header.writeUInt32BE(13, 8);
  header.write("IHDR", 12, "ascii");
  header.writeUInt32BE(width, 16);
  header.writeUInt32BE(height, 20);
  header[24] = 8;
  header[25] = 2;
  return header;
}

export function fakeJpeg(width, height, padding = 0) {
  // SOI, un APP0 (JFIF) con relleno opcional y un SOF0 con el tamaño
  const app0 = Buffer.alloc(4 + 14 + padding);
  app0.writeUInt16BE(0xffe0, 0);
  app0.writeUInt16BE(2 + 14 + padding, 2);
  app0.write("JFIF\0", 4, "ascii");
  const sof = Buffer.alloc(2 + 17);
  sof.writeUInt16BE(0xffc0, 0);
  sof.writeUInt16BE(17, 2);
  sof[4] = 8;
  sof.writeUInt16BE(height, 5);
  sof.writeUInt16BE(width, 7);
  sof[9] = 3;
  return Buffer.concat([Buffer.from([0xff, 0xd8]), app0, sof, Buffer.from([0xff, 0xd9])]);
}

export function fakeWebp(width, height) {
  const buffer = Buffer.alloc(30);
  buffer.write("RIFF", 0, "ascii");
  buffer.writeUInt32LE(22, 4);
  buffer.write("WEBP", 8, "ascii");
  buffer.write("VP8X", 12, "ascii");
  buffer.writeUInt32LE(10, 16);
  buffer.writeUIntLE(width - 1, 24, 3);
  buffer.writeUIntLE(height - 1, 27, 3);
  return buffer;
}
